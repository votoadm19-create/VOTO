CREATE TABLE IF NOT EXISTS products (
    id TEXT PRIMARY KEY,
    nome TEXT NOT NULL,
    cat TEXT,
    preco NUMERIC(12,2) NOT NULL DEFAULT 0,
    de NUMERIC(12,2),
    v TEXT,
    art TEXT,
    cor TEXT,
    foto TEXT,
    descricao TEXT,
    badge TEXT,
    estoque INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    telefone TEXT,
    cpf TEXT,
    foto TEXT,
    senha TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS admins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL UNIQUE,
    nome TEXT,
    senha TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER REFERENCES customers(id) ON DELETE SET NULL,
    cliente_nome TEXT,
    cliente_email TEXT,
    cliente_telefone TEXT,
    itens TEXT NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
    frete NUMERIC(12,2) NOT NULL DEFAULT 0,
    total NUMERIC(12,2) NOT NULL DEFAULT 0,
    cidade TEXT,
    status TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    tipo TEXT NOT NULL,
    user_id INTEGER NOT NULL,
    expira_em BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id TEXT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    customer_nome TEXT,
    nota INTEGER NOT NULL,
    comentario TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (product_id, customer_id)
);

CREATE TABLE IF NOT EXISTS favorites (
    customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    product_id TEXT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (customer_id, product_id)
);

CREATE TABLE IF NOT EXISTS settings (
    chave TEXT PRIMARY KEY,
    valor TEXT
);

CREATE TABLE IF NOT EXISTS coupons (
    code TEXT PRIMARY KEY,
    kind TEXT NOT NULL DEFAULT 'promo',
    nome TEXT NOT NULL,
    email TEXT,
    cidade TEXT,
    pix_chave TEXT,
    pix_tipo TEXT,
    desconto NUMERIC(12,4) NOT NULL DEFAULT 0,
    credito NUMERIC(12,4) NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS influencers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    senha TEXT NOT NULL,
    telefone TEXT,
    cpf TEXT,
    cidade TEXT,
    rede TEXT,
    usuario_rede TEXT,
    seguidores TEXT,
    pix_tipo TEXT,
    pix_chave TEXT,
    coupon_code TEXT REFERENCES coupons(code) ON DELETE SET NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    influencer_id INTEGER NOT NULL REFERENCES influencers(id) ON DELETE CASCADE,
    valor NUMERIC(12,2) NOT NULL DEFAULT 0,
    pago_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hubs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    cmv NUMERIC(12,2) NOT NULL DEFAULT 0,
    entrega_pct NUMERIC(12,2) NOT NULL DEFAULT 0,
    imposto_pct NUMERIC(12,2) NOT NULL DEFAULT 0,
    fixo NUMERIC(12,2) NOT NULL DEFAULT 0,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hub_cities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
    cidade TEXT NOT NULL,
    taxa NUMERIC(12,2) NOT NULL DEFAULT 0,
    UNIQUE (hub_id, cidade)
);

CREATE TABLE IF NOT EXISTS hub_stock (
    product_id TEXT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
    qtd INTEGER NOT NULL DEFAULT 0,
    custo NUMERIC(12,2),
    minimo INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (product_id, hub_id)
);

CREATE TABLE IF NOT EXISTS perso_niveis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    descricao TEXT,
    preco NUMERIC(12,2) NOT NULL DEFAULT 0
);

